/// Najde cvik v katalogu nebo mezi vlastními cviky.
Exercise? findExercise(String id, Iterable<Exercise> custom) {
  for (final e in custom) {
    if (e.id == id) return e;
  }
  for (final e in builtInExercises) {
    if (e.id == id) return e;
  }
  return null;
}

